#!/usr/bin/env python3
"""Build the run kit's AGENTS.md + output schema for the LLIoT-method experiment.

docs/plans/PLAN_lliot_method_comparison.md runs one Codex model over sampled CVEs, open world
(no category given), under OUR rubric. This script assembles the instructions that model sees,
so the prompt is generated, never hand-edited, and its hash can be pre-registered.

What is copied VERBATIM from data/difference/CLASSIFICATION_PROMPT.md (so the model judges by
exactly our definition):
    "What "home IoT device" means"   and   "Calibration rules"
    (minus one pipeline-only bullet about human routing — see DROPPED_BULLET)
What is REPLACED (pipeline framing that does not apply to an open-world, single-model run):
    "Your task", "Blind-judgment principle", "Per-category scope", "Output — three fields"
All 24 scope_note values from data/categories.csv are inlined verbatim.

Fails if the rubric's section headings change, so a rubric edit can't silently drop a section.

Outputs (deterministic — rerunning on an unchanged rubric gives byte-identical files):
    data/lliot-comparison/run-kit/AGENTS.md
    data/lliot-comparison/run-kit/schema.json
    data/lliot-comparison/run-kit/job_preamble.txt   (the line before each job's JSON on stdin)

Usage:
    python3 scripts/lliot_build_prompt.py            # write both, print SHA-256s
    python3 scripts/lliot_build_prompt.py --check    # exit 1 if the files on disk are stale
"""
import argparse
import csv
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUBRIC = os.path.join(ROOT, "data", "difference", "CLASSIFICATION_PROMPT.md")
CATEGORIES = os.path.join(ROOT, "data", "categories.csv")
KIT = os.path.join(ROOT, "data", "lliot-comparison", "run-kit")

VERBATIM = ['What "home IoT device" means', "Calibration rules"]
REPLACED = ["Your task", "Blind-judgment principle (non-negotiable)",
            "Per-category scope (read this before judging)", "Output — three fields"]
# True in the pipeline (only reasoned rows reach the human queue), false here.
DROPPED_BULLET = "- A `Maybe` or a Low-confidence `No` is more useful than a confident wrong answer"

HEADER = """\
# Instructions — home IoT CVE classification

<!-- GENERATED by scripts/lliot_build_prompt.py from data/difference/CLASSIFICATION_PROMPT.md
     and data/categories.csv. Do not edit by hand; regenerate. -->

## Your task
Each message gives you one or more CVEs as a JSON array of objects with the fields `cve_id`,
`description` and `cpe_strings` (pipe-separated CPE 2.3 strings; may be empty). For **each**
CVE, decide whether it affects a **home IoT device**, as defined below. If it does, list every
one of the 24 categories below that the affected device belongs to, **most specific first**.

Judge every CVE on its own. Earlier CVEs in the same message have no bearing on later ones.

## Rules for this task
- Use **only** the `description` and `cpe_strings` you are given, plus your own knowledge.
- Do **not** run commands, read or write files, or use web search or any other tool. Answer
  directly. File names mentioned inside a scope note are background only; they are not
  available to you and you must not look for them.
"""

OUTPUT = """\
## Output
Respond with a single JSON object matching the provided schema: `{"results": [...]}` with
exactly one entry per input CVE, in input order. Each entry:
- **`cve_id`** — copied from the input.
- **`home_iot`** — `Yes` / `No` / `Maybe`
  - `Yes` — affects a home IoT device in at least one of the 24 categories.
  - `No` — does not affect a home IoT device.
  - `Maybe` — genuinely ambiguous from the description and CPE. **Always paired with Low confidence.**
- **`categories`** — category slugs from the Categories list above, most specific first. At least one for
  `Yes` (and for `Maybe`, your best guess); **empty for `No`**. A device in several product
  lines gets every slug that applies.
- **`confidence`** — `High` (clear from the description and/or CPE) or `Low` (some uncertainty).
- **`reasoning`** — one short, self-contained sentence, **always** filled, explaining the call
  from the description/CPE alone.
"""


# Sent on stdin before each job's JSON array (lliot_run.py reads it from the kit, never inlines it).
PREAMBLE = "Classify each CVE in the JSON array below, following your instructions.\n"


def sections(md):
    """Split markdown on '## ' headings -> {heading: body} (body excludes the heading line)."""
    out, cur = {}, None
    for line in md.splitlines(keepends=True):
        m = re.match(r"^## (.+?)\s*$", line)
        if m:
            cur = m.group(1)
            out[cur] = ""
        elif cur is not None:
            out[cur] += line
    return out


def drop_bullet(body, prefix):
    """Remove one top-level '- ' bullet (with its continuation lines) starting with prefix."""
    lines, out, skipping, found = body.splitlines(keepends=True), [], False, False
    for line in lines:
        if line.startswith(prefix):
            skipping, found = True, True
            continue
        if skipping and (line.startswith("- ") or not line.strip()):
            skipping = False
        if not skipping:
            out.append(line)
    if not found:
        sys.exit(f"ERROR: bullet to drop not found in rubric: {prefix!r}")
    return "".join(out)


def build():
    secs = sections(open(RUBRIC, encoding="utf-8").read())
    expected = set(VERBATIM) | set(REPLACED)
    if set(secs) != expected:
        sys.exit("ERROR: CLASSIFICATION_PROMPT.md sections changed.\n"
                 f"  expected: {sorted(expected)}\n  found:    {sorted(secs)}\n"
                 "Update VERBATIM/REPLACED in this script deliberately, then amend the plan.")

    cats = list(csv.DictReader(open(CATEGORIES, encoding="utf-8")))
    if len(cats) != 24:
        sys.exit(f"ERROR: expected 24 categories, found {len(cats)}")

    parts = [HEADER, "\n"]
    parts.append(f'## {VERBATIM[0]}\n{secs[VERBATIM[0]].strip()}\n\n')
    parts.append("## Categories — the 24 slugs and their authoritative in/out notes\n"
                 "Each category's note spells out its specific boundary. When a note conflicts "
                 "with a first impression, the note wins.\n\n")
    for c in cats:
        parts.append(f"- **`{c['slug']}`** ({c['label']}) — {c['scope_note']}\n")
    parts.append("\n")
    parts.append(OUTPUT + "\n")
    calib = drop_bullet(secs[VERBATIM[1]], DROPPED_BULLET)
    parts.append(f"## {VERBATIM[1]}\n{calib.strip()}\n")
    agents = "".join(parts)

    item = {
        "type": "object",
        "additionalProperties": False,
        "required": ["cve_id", "home_iot", "categories", "confidence", "reasoning"],
        "properties": {
            "cve_id": {"type": "string"},
            "home_iot": {"type": "string", "enum": ["Yes", "No", "Maybe"]},
            "categories": {"type": "array",
                           "items": {"type": "string", "enum": [c["slug"] for c in cats]}},
            "confidence": {"type": "string", "enum": ["High", "Low"]},
            "reasoning": {"type": "string"},
        },
    }
    schema = {"type": "object", "additionalProperties": False, "required": ["results"],
              "properties": {"results": {"type": "array", "items": item}}}
    return {"AGENTS.md": agents, "schema.json": json.dumps(schema, indent=2) + "\n",
            "job_preamble.txt": PREAMBLE}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if the files on disk are stale")
    args = ap.parse_args()

    files = build()
    stale = []
    for name, text in files.items():
        path = os.path.join(KIT, name)
        on_disk = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if args.check:
            if on_disk != text:
                stale.append(name)
        else:
            os.makedirs(KIT, exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
        print(f"{name:16s} sha256={hashlib.sha256(text.encode()).hexdigest()}")
    if stale:
        sys.exit(f"STALE: {', '.join(stale)} — rerun without --check (and amend the pre-registration)")


if __name__ == "__main__":
    main()
